def enrich_case(case: dict) -> dict:
    """按 scenario 回填 subtype / pain_points（缺失时），返回新的 dict"""
    case = dict(case)
    meta = SCENARIO_META.get(case.get("scenario", ""))
    if meta:
        if not case.get("subtype"):
            case["subtype"] = meta["subtype"]
        if not case.get("pain_points"):
            case["pain_points"] = list(meta["pain_points"])
    return case


