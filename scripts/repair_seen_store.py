# 假编号（官网检索不到），永不登记
EXCLUDED = {"2023-04-1-271-042"}


def main():
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    seen_path = os.path.join(base, "data", "seen_cases.json")

    with open(seen_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    cases = data.setdefault("cases", {})
    print(f"修复前 seen_cases: {len(cases)} 条")

    restored = 0
    for code, ts in HISTORICAL_PUSHES.items():
        if code in EXCLUDED:
            continue
        if code not in cases:
            cases[code] = {"title_hash": "", "pushed_at": ts}
            restored += 1
            print(f"  恢复 {code} @ {ts}")

    with open(seen_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"恢复 {restored} 条；修复后共 {len(cases)} 条 → {seen_path}")


if __name__ == "__main__":
    main()
